import { MusicInfos } from 'src/playlist/domain/track.entity';

// Real YouTube Music songs, looked up once when this file was written: the seed
// never calls YouTube, so it is fast, works offline and always gives the same data.
// The thumbnail is the standard YouTube one, derived from the video id.
function music(
  videoId: string,
  name: string,
  artist: string,
  duration: number,
): MusicInfos {
  return {
    videoId,
    name,
    artist,
    thumbnail: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
    duration,
  };
}

